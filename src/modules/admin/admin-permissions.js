const ROLE_ALIASES = Object.freeze({ verification: 'verification_admin', moderation: 'moderator', finance: 'finance_admin', support: 'customer_support' });
const SYSTEM_ADMIN_ROLE_NAMES = Object.freeze(['super_admin', 'operations', 'customer_support', 'moderator', 'verification_admin', 'finance_admin', 'marketing_admin', 'analytics_admin']);
const ADMIN_ROLE_NAMES = Object.freeze([...SYSTEM_ADMIN_ROLE_NAMES, ...Object.keys(ROLE_ALIASES)]);

function canonicalRole(role) {
  return ROLE_ALIASES[role] || role;
}

function permissionsForAdminRoles(roles = []) {
  const permissions = new Set();
  for (const role of roles) {
    for (const permission of ROLE_PERMISSIONS[canonicalRole(role)] || []) permissions.add(permission);
  }
  return [...permissions];
}

function isSuperAdmin(roles = []) {
  return roles.some((role) => canonicalRole(role) === 'super_admin');
}

function hasAdminPermission(roles = [], permission) {
  return isSuperAdmin(roles) || permissionsForAdminRoles(roles).includes(permission);
}

function roleDefinitions() {
  return SYSTEM_ADMIN_ROLE_NAMES.map((name) => ({ name, systemRole: true, active: true, permissions: [...new Set(ROLE_PERMISSIONS[name])] }));
}

