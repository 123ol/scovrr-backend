function permissionsForRole(role) {
  const permissions = new Set(ROLE_PERMISSIONS[role] || []);
  for (const permission of [...permissions]) {
    for (const alias of LEGACY_PERMISSION_ALIASES[permission] || []) permissions.add(alias);
  }
  for (const [legacy, canonical] of Object.entries(LEGACY_PERMISSION_ALIASES)) {
    if (canonical.every((permission) => permissions.has(permission))) permissions.add(legacy);
  }
  return [...permissions];
}

function expandPermissions(permissions = []) {
  const expanded = new Set(permissions);
  for (const permission of permissions) for (const alias of LEGACY_PERMISSION_ALIASES[permission] || []) expanded.add(alias);
  return expanded;
}

