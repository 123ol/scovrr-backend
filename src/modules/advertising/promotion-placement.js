const PLACEMENTS = Object.freeze(['DISCOVER_HOME', 'SEARCH_RESULTS', 'CATEGORY_RESULTS', 'BUSINESS_DISCOVERY', 'PRODUCT_DISCOVERY', 'SERVICE_DISCOVERY']);
const TARGET_TYPES = Object.freeze(['BUSINESS', 'PRODUCT', 'SERVICE']);

const TARGET_PLACEMENTS = Object.freeze({
  BUSINESS: new Set(['DISCOVER_HOME', 'SEARCH_RESULTS', 'CATEGORY_RESULTS', 'BUSINESS_DISCOVERY']),
  PRODUCT: new Set(['DISCOVER_HOME', 'SEARCH_RESULTS', 'CATEGORY_RESULTS', 'PRODUCT_DISCOVERY']),
  SERVICE: new Set(['DISCOVER_HOME', 'SEARCH_RESULTS', 'CATEGORY_RESULTS', 'SERVICE_DISCOVERY'])
});

function isPlacementAllowed(targetType, placement) {
  return TARGET_PLACEMENTS[targetType]?.has(placement) || false;
}

module.exports = { PLACEMENTS, TARGET_TYPES, TARGET_PLACEMENTS, isPlacementAllowed };
